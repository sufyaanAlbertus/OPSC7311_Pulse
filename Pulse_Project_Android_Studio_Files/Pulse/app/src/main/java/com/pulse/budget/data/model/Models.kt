package com.pulse.budget.data.model

/** Built-in categories. */
enum class CategoryType(val label: String) {
    HOUSING("Housing"),
    GROCERIES("Groceries"),
    TRANSPORT("Transport"),
    FOOD_DINING("Food & Dining"),
    UTILITIES("Utilities"),
    ENTERTAINMENT("Entertainment"),
    HEALTH("Health"),
    SHOPPING("Shopping"),
    EDUCATION("Education"),
    INCOME("Income"),
    SAVINGS("Savings"),
    OTHER("Other");

    companion object {
        /** Safe parse — an unknown or missing value falls back to OTHER instead of crashing. */
        fun fromName(name: String?): CategoryType =
            entries.firstOrNull { it.name == name } ?: OTHER
    }
}

enum class RecurrenceType {
    NONE, WEEKLY, MONTHLY;

    companion object {
        fun fromName(name: String?): RecurrenceType =
            entries.firstOrNull { it.name == name } ?: NONE
    }
}

data class Expense(
    /** Firestore document id. */
    val id: String = "",
    val amount: Double = 0.0,
    val category: CategoryType = CategoryType.OTHER,
    /** Set when the user picked one of their own categories (category is then OTHER). */
    val customCategoryName: String? = null,
    val dateEpochDay: Long = 0L,
    /** "HH:mm" — when the spending activity started / ended. */
    val startTime: String = "",
    val endTime: String = "",
    val description: String = "",
    /** True when a compressed receipt photo exists at users/{uid}/receipts/{id}. */
    val hasReceipt: Boolean = false,
    /** WEEKLY / MONTHLY marks this expense as a recurring "template" (own feature #2). */
    val recurrence: RecurrenceType = RecurrenceType.NONE,
    /** For auto-generated copies: the id of the template they were created from. */
    val recurringSourceId: String? = null,
    /** For templates: the last date a copy was generated up to. */
    val lastGeneratedEpochDay: Long? = null
) {
    /** Key used to group spending and look up goals: built-in -> enum name, custom -> "custom_<name>". */
    val groupKey: String get() = categoryGroupKey(category, customCategoryName)

    /** Human-readable category name for the UI. */
    val categoryLabel: String get() = customCategoryName ?: category.label

    val isRecurringTemplate: Boolean
        get() = recurrence != RecurrenceType.NONE && recurringSourceId == null

    val isAutoGenerated: Boolean get() = recurringSourceId != null
}

/** Builds the goal/grouping key for a category. */
fun categoryGroupKey(category: CategoryType, customCategoryName: String?): String =
    if (customCategoryName.isNullOrBlank()) category.name
    else "custom_" + customCategoryName.trim().lowercase().replace("/", "-")

/** A minimum AND maximum MONTHLY spending goal for one category (built-in or custom). */
data class CategoryGoal(
    val key: String = "",
    val minGoal: Double = 0.0,
    val maxGoal: Double = 0.0
)

data class CustomCategory(
    val id: String = "",
    val name: String = ""
) {
    val groupKey: String get() = categoryGroupKey(CategoryType.OTHER, name)
}

data class Badge(
    val id: String = "",
    val title: String = "",
    val description: String = "",
    val earned: Boolean = false,
    val earnedEpochDay: Long? = null
)

/** The users/{uid} document. */
data class UserProfile(
    val uid: String = "",
    val username: String = "",
    val createdAtEpochDay: Long = 0L,
    /** Small (256px) JPEG encoded as Base64, or null when no picture was chosen. */
    val profileImageBase64: String? = null,
    val minMonthlyGoal: Double = DEFAULT_MIN_MONTHLY_GOAL,
    val maxMonthlyGoal: Double = DEFAULT_MAX_MONTHLY_GOAL,
    val streakDays: Int = 0,
    val xp: Int = 0,
    val lastLogEpochDay: Long? = null
)

const val DEFAULT_MIN_MONTHLY_GOAL = 2000.0
const val DEFAULT_MAX_MONTHLY_GOAL = 10000.0

/** Total spent in one category group over a period. */
data class SpendGroup(
    val key: String,
    val label: String,
    val category: CategoryType,
    val isCustom: Boolean,
    val total: Double
)

